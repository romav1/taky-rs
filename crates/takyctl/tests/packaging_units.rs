//! S-503: the reference units in `packaging/systemd/` are exactly what
//! `sudo takyctl-rs systemd --user taky` writes for a system install (`/etc/taky/taky.conf`)
//! with the three binaries in `/usr/local/bin` (the install path used in doc/QUICKSTART.md and
//! doc/DEPLOYMENT.md).
//!
//! Regenerate after a deliberate unit change: `TAKY_BLESS=1 cargo test -p takyctl --test
//! packaging_units`.
#![allow(clippy::expect_used, clippy::unwrap_used)] // test code

use std::path::{Path, PathBuf};

use takyctl::cli::SystemdArgs;
use takyctl::systemd::{SystemdEnv, systemd_with};

const BIN_DIR: &str = "/usr/local/bin";
const UNITS: [&str; 3] = [
    "taky-rs.service",
    "taky-rs-cot.service",
    "taky-rs-dps.service",
];

fn packaging_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packaging/systemd")
}

/// Units generated by `systemd_with` (system mode, `--user taky`, DPS on), with the temporary
/// sibling-binary directory replaced by `/usr/local/bin`.
fn generated() -> Vec<(String, String)> {
    let tmp = tempfile::tempdir().unwrap();
    let bin = tmp.path().join("bin");
    std::fs::create_dir(&bin).unwrap();
    for b in ["taky-rs", "taky_dps-rs", "takyctl-rs"] {
        std::fs::write(bin.join(b), b"").unwrap();
    }
    std::fs::write(tmp.path().join("taky.conf"), "[taky]\n").unwrap();
    let mut cfg =
        taky_config::load_config_in(Some(Path::new("taky.conf")), true, tmp.path()).unwrap();
    cfg.cfg_path = Some(PathBuf::from("/etc/taky/taky.conf"));
    let units = tmp.path().join("units");
    std::fs::create_dir(&units).unwrap();
    let args = SystemdArgs {
        path: units.clone(),
        install: false,
        dps: true,
        user: Some("taky".into()),
    };
    let env = SystemdEnv {
        bin_dir: Some(bin.clone()),
        systemctl: "/nonexistent/systemctl".into(),
    };
    let (mut out, mut err) = (Vec::new(), Vec::new());
    assert_eq!(
        systemd_with(&args, &cfg, &env, &mut out, &mut err).unwrap(),
        0
    );
    assert!(err.is_empty(), "{}", String::from_utf8_lossy(&err));
    let bin_s = bin.to_string_lossy().into_owned();
    UNITS
        .iter()
        .map(|n| {
            let text = std::fs::read_to_string(units.join(n)).unwrap();
            ((*n).to_owned(), text.replace(&bin_s, BIN_DIR))
        })
        .collect()
}

#[test]
fn reference_units_equal_generated() {
    let dir = packaging_dir();
    let bless = std::env::var_os("TAKY_BLESS").is_some();
    for (name, text) in generated() {
        let p = dir.join(&name);
        if bless {
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(&p, &text).unwrap();
            continue;
        }
        let have = std::fs::read_to_string(&p)
            .unwrap_or_else(|e| panic!("{}: {e} (regenerate with TAKY_BLESS=1)", p.display()));
        assert_eq!(
            have,
            text,
            "{} differs from `takyctl-rs systemd --user taky` (regenerate with TAKY_BLESS=1)",
            p.display()
        );
    }
}

#[test]
fn reference_units_shape() {
    let g = generated();
    let get = |n: &str| &g.iter().find(|(k, _)| k == n).unwrap().1;
    assert!(
        get("taky-rs-cot.service")
            .contains("ExecStart=/usr/local/bin/taky-rs -l \"${LOG_LEVEL}\"\n")
    );
    assert!(get("taky-rs-dps.service").contains("ExecStart=/usr/local/bin/taky_dps-rs\n"));
    assert!(get("taky-rs.service").contains("Wants=taky-rs-dps.service\n"));
    for (_, t) in &g {
        assert!(!t.contains("WorkingDirectory"), "{t}");
    }
}
