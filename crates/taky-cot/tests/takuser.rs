//! Port of `taky/tests/test_takuser.py` (test-strategy §2 row 17): a field-built `TAKUser`
//! generates the `<detail>` of the fixture (`TakUser::to_element`, ARCHITECTURE §14 A.4).
#![allow(clippy::unwrap_used)]

mod common;

use common::{assert_elements_equal, parse};
use taky_cot::{TakDevice, TakUser, Teams};
use taky_xml::{SerOpts, serialize};

/// `test_takuser.py:XML_S`.
const XML_S: &str = r#"<event version="2.0" uid="TEST-deadbeef" type="a" how="m-g" time="2021-03-11T15:49:07.138Z" start="2021-03-11T15:49:07.138Z" stale="2021-03-12T15:49:07.138Z"><point lat="0.000000" lon="0.000000" hae="0.0" ce="9999999.0" le="9999999.0"/><detail><takv os="Android" version="10" device="Some Device" platform="python unittest"/><status battery="83"/><uid Droid="JENNY"/><contact callsign="JENNY" endpoint="*:-1:stcp" phone="800-867-5309"/><__group role="Team Member" name="Cyan"/><track course="90.1" speed="10.3"/></detail></event>"#;

/// `etree.tostring(tak_u.as_element)` of the test's `TAKUser` — generated by the original
/// (taky v0.9, lxml; `tools/pyref` venv, 2026-10-26). Note the `takv` attribute order differs
/// from `XML_S` (`elements_equal` compares attrib as a dict).
const GOLDEN: &str = r#"<detail><takv os="Android" device="Some Device" version="10" platform="python unittest"/><status battery="83"/><uid Droid="JENNY"/><contact callsign="JENNY" endpoint="*:-1:stcp" phone="800-867-5309"/><__group role="Team Member" name="Cyan"/><track course="90.1" speed="10.3"/></detail>"#;

/// `test_takuser.TAKUserTestcase.test_as_element`.
#[test]
fn as_element() {
    let answer = parse(XML_S).find("detail").unwrap().clone();

    let tak_u = TakUser {
        callsign: Some("JENNY".into()),
        marker: Some("a".into()),
        group: Some(Teams::Cyan),
        role: Some("Team Member".into()),
        phone: Some("800-867-5309".into()), // hahahaha
        endpoint: Some("*:-1:stcp".into()),
        course: Some(90.1),
        speed: Some(10.3),
        battery: Some("83".into()),
        device: TakDevice {
            os: Some("Android".into()),
            version: Some("10".into()),
            device: Some("Some Device".into()),
            platform: Some("python unittest".into()),
        },
        ..TakUser::default()
    };

    let got = tak_u.to_element().unwrap();
    assert_elements_equal(&answer, &got);
    // Extra (test-strategy §2): byte-level serialization equals the original's.
    assert_eq!(
        String::from_utf8(serialize(&got, &SerOpts::default())).unwrap(),
        GOLDEN
    );
}
